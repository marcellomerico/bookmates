#!/usr/bin/env bash
# Generates supabase/prod_setup.sql: every required migration for a fresh project, in order,
# inside one transaction (all or nothing). Migration 20260731150000 is skipped (superseded).
# Usage: tool/build_prod_setup.sh   (re-run after adding a migration)
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/prod_setup.sql
skip=20260731150000_fix_account_deletion.sql

n=0
{
  echo "-- GENERATED by tool/build_prod_setup.sh. Do not edit; edit the migrations instead."
  echo "-- Fresh Supabase project only. Paste into SQL Editor and run once."
  echo "begin;"
  for f in supabase/migrations/*.sql; do
    [[ "$(basename "$f")" == "$skip" ]] && continue
    printf '\n-- ===== %s =====\n' "$(basename "$f")"
    n=$((n + 1))
    cat "$f"
  done
  printf '\ncommit;\n'
} > "$out"
echo "wrote $out ($n migrations)"
